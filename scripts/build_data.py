"""Assemble data/cap149.js from the proofread OCR output (secs_f.json) and the structure/titles files.

Usage: python3 scripts/build_data.py path/to/secs_f.json path/to/structure.json
"""
import json, sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "ocr"))
import titles_tr_fa as T
import titles_ru_de as R

secs = json.load(open(sys.argv[1]))
st = json.load(open(sys.argv[2]))
tr, fa, ru, de = T.parse(T.TR), T.parse(T.FA), T.parse(R.RU), T.parse(R.DE)
parts = []
for i, (num, title, a, b) in enumerate(st["parts"]):
    parts.append({"id": num, "title": title, "title_tr": T.PARTS_TR[i], "title_fa": T.PARTS_FA[i], "title_ru": R.PARTS_RU[i], "title_de": R.PARTS_DE[i], "from": a, "to": b})
heads = {int(k): v for k, v in st["headings"].items()}
starts = {int(k): v["page"] for k, v in secs.items()}
out = []
cur_head = None
for n in range(1, 199):
    part = next(p["id"] for p in parts if p["from"] <= n <= p["to"])
    if n in heads: cur_head = heads[n]
    if any(p["from"] == n for p in parts) and n not in heads: cur_head = None
    a = starts[n]; b = starts.get(n + 1, 46)
    out.append({"n": n, "title": st["titles"][str(n)], "title_tr": tr[n], "title_fa": fa[n], "title_ru": ru[n], "title_de": de[n], "part": part,
                "heading": heads.get(n), "heading_i18n": R.HEADINGS.get(n), "group": cur_head, "pages": list(range(a, max(a, b) + 1)), "text": secs[str(n)]["paras"]})
law = {
    "meta": {
        "title": "Contract Law, Cap. 149",
        "edition": "Laws of Cyprus, Revised Edition 1959",
        "commencement": "1 January 1931",
        "origin": "Contract Law 1930 (Law 24 of 1930); 1959 edition cites 1949 Cap. 192, 25 of 1953 and 7 of 1956",
    },
    "parts": parts,
    "sections": out,
    "endnote": ("Section 247 of this Law which repealed the Commercial Code (Amendment) Law 1917 and some provisions of the Mejelle "
                "and the Ottoman Commercial Code, provided that such repeal should not, and that nothing in the Law should, affect:— "
                "(a) any contract, agreement, bond or instrument entered into, made or executed before the coming into operation of this Law; or "
                "(b) any right or interest acquired or accrued under the provisions of any enactment repealed by this Law; or "
                "(c) any legal proceeding or remedy in respect of any such contract, agreement, bond, instrument, right or interest."),
}
with open(os.path.join(os.path.dirname(__file__), "..", "data", "cap149.js"), "w", encoding="utf-8") as f:
    f.write("// Contract Law, Cap. 149 (Laws of Cyprus, 1959 edition). Generated by scripts/build_data.py, do not edit by hand.\n")
    f.write("export const LAW = " + json.dumps(law, ensure_ascii=False, indent=1) + ";\n")
print("sections", len(out), "words", sum(len(" ".join(s["text"]).split()) for s in out))
